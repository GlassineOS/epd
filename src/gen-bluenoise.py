"""gen-bluenoise: the staggered cuts' phase pattern.

A 64 x 64 blue-noise rank map by void-and-cluster (Ulichney 1993), toroidal,
deterministic (fixed seed). Every pixel of a 64 x 64 panel tile gets a rank
0..4095; phase group g of G is the rank range [g * 4096 / G, (g + 1) * 4096 / G),
so every G (2..9 for A2/2..A2/9) gets an even, blue-noise spread of groups
from the one map.

Word-stratified (the default): every wire word (8 x 1 pixels,
x aligned to 8) holds one rank of each octant [k * 512, (k + 1) * 512), so a
word has exactly 8 / G pixels of each group for G = 2, 4, 8 (at most one for
16, an even split +-1 for the rest). The GPU pass loops over a word's pixels
on their group's frame: with the free map the busiest word of a wave set the
loop count (A509). The swaps of the initial pattern stay inside a
word, the voids are filled only in words still missing the rank's octant.
--free: the unconstrained map.

  gen-bluenoise.py > epd-bluenoise.h
"""
import sys
import numpy as np

N = 64
SIGMA = 1.5


def kernel():
    d = np.arange(N)
    d = np.minimum(d, N - d)
    g = np.exp(-(d[:, None] ** 2 + d[None, :] ** 2) / (2 * SIGMA ** 2))
    return np.fft.rfft2(g)


K = kernel()


def energy(m):
    return np.fft.irfft2(np.fft.rfft2(m) * K, s=m.shape)


def tightest(m, ok=None):   # the densest 1 (cluster)
    e = energy(m)
    e[m == 0] = -np.inf
    if ok is not None:
        e[~ok] = -np.inf
    return np.unravel_index(np.argmax(e), m.shape)


def largest_void(m, ok=None):   # the emptiest 0 (void), among ok
    e = energy(m)
    e[m == 1] = np.inf
    if ok is not None:
        e[~ok] = np.inf
    return np.unravel_index(np.argmin(e), m.shape)


def word_mask(y, x):        # the pixels of (y, x)'s word
    ok = np.zeros((N, N), bool)
    ok[y, x // 8 * 8:x // 8 * 8 + 8] = True
    return ok


def main_words():
    rng = np.random.default_rng(12345)
    m = np.zeros((N, N), np.uint8)
    for y in range(N):          # octant 0: one pixel per word
        for w in range(N // 8):
            m[y, w * 8 + rng.integers(8)] = 1
    for it in range(20 * N * N):    # move clusters into voids, inside their word
        c = tightest(m)
        m[c] = 0
        v = largest_void(m, word_mask(*c))
        m[v] = 1
        if v == c:
            break
    rank = np.zeros((N, N), np.int32)
    p = m.copy()
    n0 = N * N // 8
    for r in range(n0 - 1, -1, -1):
        c = tightest(p)
        p[c] = 0
        rank[c] = r
    p = m.copy()
    for k in range(1, 8):           # octant k: one more pixel per word
        need = np.ones((N, N // 8), bool)
        for r in range(k * n0, (k + 1) * n0):
            ok = np.repeat(need, 8, axis=1)
            v = largest_void(p, ok)
            p[v] = 1
            rank[v] = r
            need[v[0], v[1] // 8] = False
    return rank


def check_words(rank):
    o = rank.reshape(N, N // 8, 8) >> 9
    assert (np.sort(o, axis=2) == np.arange(8)).all()


def main_free():
    rng = np.random.default_rng(12345)
    n0 = N * N // 10
    m = np.zeros((N, N), np.uint8)
    m.flat[rng.choice(N * N, n0, replace=False)] = 1
    while True:                 # the initial binary pattern: move clusters into voids
        c = tightest(m)
        m[c] = 0
        v = largest_void(m)
        if v == c:
            m[c] = 1
            break
        m[v] = 1
    rank = np.zeros((N, N), np.int32)
    p = m.copy()
    for r in range(n0 - 1, -1, -1):     # phase 1: remove the tightest, ranks below n0
        c = tightest(p)
        p[c] = 0
        rank[c] = r
    p = m.copy()
    for r in range(n0, N * N):          # phases 2 + 3: fill the largest voids
        v = largest_void(p)
        p[v] = 1
        rank[v] = r
    return rank


def main():
    free = "--free" in sys.argv[1:]
    rank = main_free() if free else main_words()
    assert sorted(rank.flat) == list(range(N * N))
    if not free:
        check_words(rank)
    pos = np.zeros(N * N, np.int32)
    for y in range(N):
        for x in range(N):
            pos[rank[y, x]] = y * N + x
    print("/* SPDX-License-Identifier: GPL-2.0-or-later */")
    print("/* Copyright GlassineOS contributors */")
    print("/* epd-bluenoise.h - generated by gen-bluenoise.py (do not edit): the")
    print(" * staggered cuts' phase pattern. epd_bn_rank[y][x] = the blue-noise rank of")
    print(" * pixel (x, y) of a 64 x 64 tile; epd_bn_pos[rank] = y * 64 + x. Group g of G:")
    print(" * ranks [g * 4096 / G, (g + 1) * 4096 / G)" + ("" if free else ". Word-stratified: every 8 x 1 word"))
    if not free:
        print(" * (x aligned to 8) holds one rank of each octant [k * 512, (k + 1) * 512)")
    print(" */")
    print("#ifndef EPD_BLUENOISE_H\n#define EPD_BLUENOISE_H\n#include <stdint.h>")
    print("#define EPD_BN 64")
    print("static const uint16_t epd_bn_rank[EPD_BN][EPD_BN] = {")
    for y in range(N):
        print("    { " + ", ".join(str(int(v)) for v in rank[y]) + " },")
    print("};")
    print("static const uint16_t epd_bn_pos[EPD_BN * EPD_BN] = {")
    for i in range(0, N * N, 32):
        print("    " + ", ".join(str(int(v)) for v in pos[i:i + 32]) + ",")
    print("};\n#endif")


main()
